#!/usr/bin/env bun
/**
 * Regenerate the TypeScript protocol interfaces from the single proto authority.
 *
 * The proto file is the only source: this script runs `protoc` with the `ts-proto` plugin and
 * writes the result to `packages/protocol/src/generated.ts`. Nothing here hand-writes a DTO
 * model, and the output is *interfaces only* — no encode/decode functions, no runtime
 * dependency, no JSON coercers. A runtime decoder would be a second implementation of the
 * wire format beside the generated Rust one.
 *
 * ## Toolchain
 *
 * `ts-proto` is installed in an **isolated** tooling directory outside the repository
 * (`protocol-tooling`, via pnpm) so the repo keeps no Node manifest or lockfile change. The
 * plugin path is resolved explicitly and its version pinned below; there is no implicit
 * "latest" and no credential is read.
 *
 * Use from a checkout whose sibling `protocol-tooling` exists:
 *
 *   bun tools/generate-sage-db-protocol.ts            # write generated.ts
 *   bun tools/generate-sage-db-protocol.ts --check    # compare only, exit 1 on drift
 *
 * `--check` generates into a temp directory and byte-compares it with the checked-in file, so
 * a proto change that was not regenerated fails rather than drifting silently.
 */

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";

/** Pinned generator identity. A different version must be a deliberate edit here. */
export const TS_PROTO_VERSION = "2.6.1";
/** Pinned protoc the generated header records; keep in step with the host compiler. */
export const PROTOC_VERSION = "7.36.0";

const REPO = resolve(import.meta.dir, "..");
const PROTO_ROOT = join(REPO, "sage-db", "proto");
const PROTO_FILE = "sage/v1/service.proto";
const OUT_FILE = join(REPO, "packages", "protocol", "src", "generated.ts");

/**
 * Where the isolated pnpm install lives, relative to the repository.
 *
 * The tooling directory is a sibling of the *workspace*, not of this checkout: this repo sits
 * at `<session>/protocol-author/repo`, so the candidates walk up accordingly. Discovery is
 * explicit rather than relying on `node_modules` resolution, because the repository must stay
 * free of a Node manifest and the plugin must be a pinned, known path.
 */
const TOOLING_CANDIDATES = [
  join(REPO, "..", "..", "protocol-tooling"),
  join(REPO, "..", "protocol-tooling"),
  join(REPO, "protocol-tooling"),
];

/** The banner written above the generated body, so provenance travels with the file. */
function banner(): string {
  return [
    "// Code generated by tools/generate-sage-db-protocol.ts. DO NOT EDIT.",
    `//   proto:          ${PROTO_FILE}`,
    `//   ts-proto:       v${TS_PROTO_VERSION}`,
    `//   protoc:         v${PROTOC_VERSION}`,
    "//",
    "// Interfaces only: no encode/decode functions, no runtime dependency, no JSON coercers.",
    "// 64-bit ids, versions and revisions are `string`, because a JSON number would round them.",
    "",
  ].join("\n");
}

function findProtoc(): string {
  const override = process.env["SAGE_DB_PROTOC"];
  if (override !== undefined && existsSync(override)) return override;
  const homebrew = "/opt/homebrew/bin/protoc";
  if (existsSync(homebrew)) return homebrew;
  return "protoc";
}

function findPlugin(): string {
  const explicit = process.env["SAGE_DB_TS_PROTO_PLUGIN"];
  if (explicit !== undefined) {
    if (!existsSync(explicit)) throw new Error("SAGE_DB_TS_PROTO_PLUGIN does not name an existing plugin");
    return resolve(explicit);
  }
  for (const dir of TOOLING_CANDIDATES) {
    const plugin = join(dir, "node_modules", ".bin", "protoc-gen-ts_proto");
    if (existsSync(plugin)) return plugin;
  }
  throw new Error(
    "protoc-gen-ts_proto not found. Install the isolated tooling first:\n" +
      "  mkdir -p protocol-tooling && cd protocol-tooling\n" +
      `  printf '{"name":"sage-db-protocol-tooling","private":true}\\n' > package.json\n` +
      `  pnpm add --save-exact ts-proto@${TS_PROTO_VERSION}`,
  );
}

/** Generate into `outDir` and return the path of the single output file. */
function generate(outDir: string): string {
  const plugin = findPlugin();
  const protoc = findProtoc();
  const version = spawnSync(protoc, ["--version"], { encoding: "utf8" });
  if (version.status !== 0 || version.stdout.trim() !== "libprotoc 36.0") {
    throw new Error("Protocol generation requires exactly libprotoc 36.0; set SAGE_DB_PROTOC to the verified compiler");
  }
  const installed = JSON.parse(readFileSync(resolve(dirname(plugin), "..", "ts-proto", "package.json"), "utf8")) as { version?: unknown };
  if (installed.version !== TS_PROTO_VERSION) {
    throw new Error(`Protocol generation requires ts-proto ${TS_PROTO_VERSION}`);
  }
  // `onlyTypes` produces interfaces without runtime helpers; the remaining flags switch off
  // the optional code paths that would otherwise emit encoders, JSON methods and clients.
  const options = [
    "onlyTypes",
    "esModuleInterop=false",
    "outputEncodeMethods=false",
    "outputJsonMethods=false",
    "outputClientImpl=false",
    "stringEnums=false",
  ].join(",");
  const result = spawnSync(
    protoc,
    [
      `--plugin=protoc-gen-ts_proto=${plugin}`,
      `--ts_proto_out=${outDir}`,
      `--ts_proto_opt=${options}`,
      `-I`,
      PROTO_ROOT,
      PROTO_FILE,
    ],
    { encoding: "utf8" },
  );
  if (result.status !== 0) {
    throw new Error(`protoc failed (${result.status}): ${result.stderr ?? ""}`);
  }
  return join(outDir, "sage", "v1", "service.ts");
}

/** The complete generated file: banner plus protoc's body. */
function render(): string {
  const work = mkdtempSync(join(tmpdir(), "sage-proto-"));
  try {
    const produced = generate(work);
    return banner() + readFileSync(produced, "utf8");
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

function main(argv: readonly string[]): number {
  const check = argv.includes("--check");
  const content = render();
  if (check) {
    if (!existsSync(OUT_FILE)) {
      process.stderr.write(`missing ${OUT_FILE}; run without --check to generate it\n`);
      return 1;
    }
    const current = readFileSync(OUT_FILE, "utf8");
    if (current !== content) {
      process.stderr.write(
        `${OUT_FILE} is stale against ${PROTO_FILE}. Regenerate:\n` +
          "  bun tools/generate-sage-db-protocol.ts\n",
      );
      return 1;
    }
    process.stdout.write(`${OUT_FILE} is up to date\n`);
    return 0;
  }
  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, content, "utf8");
  process.stdout.write(`wrote ${OUT_FILE}\n`);
  return 0;
}

if (import.meta.main) {
  process.exit(main(process.argv.slice(2)));
}
