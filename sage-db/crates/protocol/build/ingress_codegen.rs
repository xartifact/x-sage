//! Build-time generator: descriptor-driven `DeserializeSeed` implementations.
//!
//! # One authority
//!
//! This module reads the **same** `sage_descriptor.bin` that `prost-build` and `pbjson-build`
//! consume, and emits one admitted seed per message into `OUT_DIR`. It never invents a field
//! table: names, numbers, `json_name` aliases, label (repeated/optional), type and oneof
//! membership all come from the descriptor.
//!
//! # Fail-closed
//!
//! A field kind or feature this generator does not implement is a **build error**, never a
//! silent fall back to the ordinary infallible `Deserialize`. That is the difference between
//! "we admit this input" and "we admit the inputs we happened to generate for".
//!
//! # What it emits
//!
//! For each message `<M>` in package `sage.v1`:
//!
//! * `impl DeserializeSeed<'de> for <M>Seed` producing `Decoded<M>`;
//! * `impl RetainedExtent for M` summing real `String`/`Vec` capacities;
//! * a request-shaped wrapper is added by the runtime for the named entry points.
//!
//! The seed's shape mirrors `pbjson` deliberately — same alias pair, same duplicate rule, same
//! null handling, same default-when-absent — because the differential suite compares the two.

use std::fmt::Write as _;
use std::path::Path;

use prost_types::{DescriptorProto, FieldDescriptorProto, FileDescriptorSet};

/// Generate seeds for every message in the descriptor set at `descriptor_path`.
///
/// # Errors
///
/// A `panic!` on any unsupported field kind, which fails the build. The generator is a build
/// step; a partially generated crate would be worse than a failed one.
pub(crate) fn generate(descriptor_path: &Path, out_dir: &Path) {
    let bytes = std::fs::read(descriptor_path)
        .unwrap_or_else(|error| panic!("read {}: {error}", descriptor_path.display()));
    let set = FileDescriptorSet::decode(bytes.as_slice())
        .unwrap_or_else(|error| panic!("decode descriptor set: {error}"));

    let mut out = String::new();
    out.push_str(
        "// @generated by build/ingress_codegen.rs from sage_descriptor.bin — do not edit.\n\
         use crate::ingress::{Decoded, DecodeState, RetainedExtent};\n\
         use crate::generated::*;\n\
         use serde::de::{DeserializeSeed, Error as _, MapAccess, Visitor};\n\
         use std::marker::PhantomData;\n\n",
    );

    let mut wrappers = String::new();
    wrappers.push_str(
        "// @generated by build/ingress_codegen.rs from sage_descriptor.bin — do not edit.\n\
         // Public one-call decode wrappers, one per protocol message. Each owns its whole decode\n\
         // frame and returns an owned `Decoded<T>`, so a caller never assembles a policy, context\n\
         // or state.\n\n",
    );

    for file in &set.file {
        let package = file.package();
        if package != "sage.v1" {
            continue;
        }
        for message in &file.message_type {
            // Fail closed on a nested message rather than silently omitting it: the current
            // schema has none, and a future one must be generated correctly or stop the build.
            if !message.nested_type.is_empty() {
                panic!(
                    "nested message types are not supported yet (message `{}`); refusing to                      silently skip them",
                    message.name()
                );
            }
            emit_message(&mut out, message, None);
            emit_wrapper(&mut wrappers, message);
        }
    }

    let path = out_dir.join("ingress_seeds.rs");
    std::fs::write(&path, out).unwrap_or_else(|error| panic!("write {}: {error}", path.display()));
    let wrappers_path = out_dir.join("ingress_wrappers.rs");
    std::fs::write(&wrappers_path, wrappers)
        .unwrap_or_else(|error| panic!("write {}: {error}", wrappers_path.display()));
}

/// The supported proto field kinds, resolved from the descriptor type enum.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Kind {
    Uint32,
    Uint64,
    String,
    Enum,
    Message,
}

fn kind_of(field: &FieldDescriptorProto) -> Kind {
    use prost_types::field_descriptor_proto::Type as T;
    match field.r#type() {
        T::Uint32 => Kind::Uint32,
        T::Uint64 => Kind::Uint64,
        T::String => Kind::String,
        T::Enum => Kind::Enum,
        T::Message => Kind::Message,
        // Everything else is an unimplemented feature and must fail the build rather than
        // degrade to the ordinary infallible decoder.
        other => panic!(
            "ingress_codegen: unsupported field type {other:?} on {}.{} — \
             implement it or remove it from the protocol; falling back to ordinary Deserialize \
             would silently break the admission contract",
            field.extendee(),
            field.name()
        ),
    }
}

fn pascal(name: &str) -> String {
    use heck::ToUpperCamelCase;
    name.to_upper_camel_case()
}

fn snake(name: &str) -> String {
    use heck::ToSnakeCase;
    name.to_snake_case()
}

// The emitter writes many small line fragments into one string; `write!` ending in a newline is
// the natural form here and `writeln!` would obscure the generated layout.
#[allow(clippy::write_with_newline)]
fn emit_message(out: &mut String, message: &DescriptorProto, _parent: Option<&str>) {
    let name = message.name();
    let module = snake(name);
    let ty = pascal(name);

    // A message with no fields still needs a seed that refuses unknown keys and defaults.
    let mut fields = String::new();
    let mut aliases = String::new();
    let mut field_enum = String::new();
    let mut defaults = String::new();
    let mut extent = String::new();
    let mut duplicate_guards = String::new();

    // prost collapses each `oneof` into ONE struct field of type `Option<oneof::Enum>`; every
    // member shares that slot. Group members by index so the generated arms set the same slot, and
    // a second member of an already-set oneof is a duplicate — which matches pbjson, which keeps
    // the whole slot as `Option` and refuses a second write.
    let oneof_names: Vec<String> = message
        .oneof_decl
        .iter()
        .map(|decl| snake(decl.name()))
        .collect();

    for field in &message.field {
        let id = u32::try_from(field.number()).expect("field number fits u32");
        let proto_name = field.name();
        let json = field.json_name();
        let rust = snake(proto_name);
        let variant = format!("F{}", pascal(proto_name));
        let kind = kind_of(field);
        let elem = elem_type(kind, field);
        let repeated = field.label() == prost_types::field_descriptor_proto::Label::Repeated;
        // A `proto3_optional` field gets a SYNTHETIC oneof; prost flattens it to a plain
        // `Option<T>` and emits no nested enum module, so it must not be treated as a real
        // oneof member here.
        let oneof_index = if field.proto3_optional() {
            None
        } else {
            field.oneof_index.and_then(|i| usize::try_from(i).ok())
        };
        // prost's typing: a singular MESSAGE is `Option<T>`; a `proto3_optional` scalar is
        // `Option<T>`; a oneof member lives in its oneof's `Option<variant>`; everything else is a
        // plain value.
        let presence = !repeated
            && oneof_index.is_none()
            && (kind == Kind::Message || field.proto3_optional());

        if json == proto_name {
            let _ = write!(
                aliases,
                "            {json:?} => Ok(GeneratedField::{variant}),\n"
            );
        } else {
            let _ = write!(
                aliases,
                "            {json:?} | {proto_name:?} => Ok(GeneratedField::{variant}),\n"
            );
        }
        let _ = write!(
            field_enum,
            "        /// One accepted field name.\n        {variant},\n"
        );

        // Decode the value into `value`, admitting inside the seed where the seed owns the
        // allocation (strings), and admitting the slot for everything else.
        let (admit, value_expr) = match kind {
            // `presence` here means the field is `proto3_optional`, so `null` is absence. A
            // REQUIRED string must refuse `null`, exactly as pbjson's `next_value::<String>()`.
            Kind::String if presence => (
                String::new(),
                format!(
                    "map_.next_value_seed(crate::ingress::StringSeed {{ state, field: {id} }})?"
                ),
            ),
            Kind::String => (
                String::new(),
                format!(
                    "map_.next_value_seed(crate::ingress::RequiredStringSeed {{ state, field: {id} }})?"
                ),
            ),
            Kind::Message if oneof_index.is_some() => (
                String::new(),
                // A oneof arm holds the message directly, so it must not unwrap an Option.
                format!(
                    "map_.next_value_seed(crate::ingress::OneofMessageSeed::new(crate::ingress::seeds::{module}_seed::{elem}Seed {{ state }}))?",
                    module = snake(&elem)
                ),
            ),
            Kind::Message => (
                String::new(),
                // A singular message field is nullable; its seed yields `Option<T>`.
                format!(
                    "map_.next_value_seed(crate::ingress::MessageSeed::new(crate::ingress::seeds::{module}_seed::{elem}Seed {{ state }}))?",
                    module = snake(&elem)
                ),
            ),
            // A `proto3_optional` enum is nullable in pbjson.
            Kind::Enum if presence => (
                format!(
                    "                        state.charge_work({id}).map_err(A::Error::custom)?;\n"
                ),
                format!(
                    "map_.next_value_seed(crate::ingress::OptionalEnumSeed::<crate::generated::{enum_ty}>::new())?",
                    enum_ty = enum_type_of(field)
                ),
            ),
            Kind::Enum => (
                // An enum field is `i32` INLINE in the DTO: it retains no heap, so it admits no
                // heap slot. Its visit is charged as WORK entries on the shared ledger.
                format!(
                    "                        state.charge_work({id}).map_err(A::Error::custom)?;\n"
                ),
                format!(
                    "map_.next_value_seed(crate::ingress::EnumSeed::<crate::generated::{enum_ty}>::new())?",
                    enum_ty = enum_type_of(field)
                ),
            ),
            // A `proto3_optional` scalar is nullable in pbjson.
            _ if presence => (
                format!(
                    "                        state.charge_work({id}).map_err(A::Error::custom)?;\n"
                ),
                format!("map_.next_value_seed(crate::ingress::OptionalIntSeed::<{elem}>::new())?"),
            ),
            _ => (
                // Same for every scalar: inline, zero heap, work entries only.
                format!(
                    "                        state.charge_work({id}).map_err(A::Error::custom)?;\n"
                ),
                format!("map_.next_value_seed(crate::ingress::IntegerSeed::<{elem}>::new())?"),
            ),
        };

        let dup_text = |name: &str| {
            format!(
                "                        if {name} {{\n                            \
             return Err(A::Error::custom(\"duplicate field\"));\n                        \
             }}\n"
            )
        };

        let (store, dup) = if let Some(idx) = oneof_index {
            let slot = &oneof_names[idx];
            let enum_name = pascal(message.oneof_decl[idx].name());
            // A oneof member is nullable in pbjson: `null` leaves the slot unset, so the guard is
            // on the SLOT (shared by every member) and a later member is still allowed.
            let store = match kind {
                Kind::Message => format!(
                    "                        if let Some(inner) = value {{\n                            \
             {slot}__ = Some(crate::generated::{mm}::{en}::{member}(inner));\n                        \
             }}\n",
                    mm = snake(message.name()),
                    en = enum_name,
                    member = pascal(proto_name)
                ),
                _ => format!(
                    "                        if let Some(inner) = value {{\n                            \
             {slot}__ = Some(crate::generated::{mm}::{en}::{member}(inner));\n                        \
             }}\n",
                    mm = snake(message.name()),
                    en = enum_name,
                    member = pascal(proto_name)
                ),
            };
            (store, dup_text(&format!("{slot}__.is_some()")))
        } else if repeated {
            (
                format!(
                    "                        {rust}__ = map_.next_value_seed(crate::ingress::VecSeed::new(state, {id}, {make}))?;\n                        {rust}__seen = true;\n",
                    make = repeated_element_maker(kind, &elem)
                ),
                // pbjson keeps the slot as `Option<Vec<_>>`, so an EMPTY decoded array still marks
                // the field present; a second occurrence is a duplicate.
                dup_text(&format!("{rust}__seen")),
            )
        } else if presence {
            // A nullable field (`proto3_optional` scalar, enum, message, or optional string):
            // `null` is absence. EVERY seed on this path yields `Option<_>`, so it stores as-is.
            let store = format!("                        {rust}__ = value;\n");
            (store, dup_text(&format!("{rust}__.is_some()")))
        } else {
            // A required String still comes back as `Option<String>` (the seed is nullable so one
            // code path serves both); a non-optional field materialises its default when absent,
            // exactly as pbjson's `unwrap_or_default` does. A scalar keeps the usual seen-flag.
            // The temporary is `Option<T>` for every kind, so a required field stores it as-is
            // and the constructor applies `unwrap_or_default` exactly where pbjson does.
            // The temporary is `Option<T>` for every kind (`Some(value)` marks presence), and
            // the constructor applies `unwrap_or_default` exactly where pbjson does.
            let store = format!(
                "                        {rust}__ = Some(value);\n                        {rust}__seen = true;\n"
            );
            (store, dup_text(&format!("{rust}__seen")))
        };

        let bind = if repeated {
            String::new()
        } else {
            format!("                        let value = {value_expr};\n")
        };

        let _ = write!(
            duplicate_guards,
            "                    GeneratedField::{variant} => {{\n{dup}{bind}{admit}{store}                    }}\n",
            dup = dup,
            bind = bind,
            admit = admit,
            store = store,
        );

        if repeated {
            let _ = write!(
                defaults,
                "            let mut {rust}__: Vec<{elem}> = Vec::new();\n            let mut {rust}__seen = false;\n"
            );
            let _ = write!(
                extent,
                "        total = crate::ingress::add_checked(total, crate::ingress::vec_extent(&self.{rust})?)?;\n"
            );
        } else if let Some(idx) = oneof_index {
            let slot = &oneof_names[idx];
            if !defaults.contains(&format!("let mut {slot}__")) {
                let _ = write!(
                    defaults,
                    "            let mut {slot}__: Option<crate::generated::{message_module}::{enm}> = None;\n",
                    message_module = snake(message.name()),
                    enm = pascal(message.oneof_decl[idx].name())
                );
            }
            let _ = write!(
                extent,
                "        total = crate::ingress::add_checked(total, crate::ingress::opt_extent(&self.{slot})?)?;\n"
            );
        } else if presence {
            let _ = write!(
                defaults,
                "            let mut {rust}__: Option<{elem}> = None;\n"
            );
            let _ = write!(
                extent,
                "        total = crate::ingress::add_checked(total, crate::ingress::opt_extent(&self.{rust})?)?;\n"
            );
        } else {
            let _ = write!(
                defaults,
                "            let mut {rust}__: Option<{elem}> = None;\n            let mut {rust}__seen = false;\n"
            );
            let _ = write!(
                extent,
                "        total = crate::ingress::add_checked(total, crate::ingress::value_extent(&self.{rust})?)?;\n"
            );
        }
    }

    // The struct literal must name EVERY generated field, in descriptor order, matching prost's
    // typing exactly: one name per oneof SLOT (not per member), and one per ordinary field.
    let mut ctor = format!("crate::generated::{ty} {{ ");
    let mut emitted_oneofs: Vec<String> = Vec::new();
    for field in &message.field {
        if let Some(idx) = field.oneof_index.and_then(|i| usize::try_from(i).ok()) {
            let slot = snake(message.oneof_decl[idx].name());
            if !emitted_oneofs.contains(&slot) {
                let _ = write!(ctor, "{slot}: {slot}__, ");
                emitted_oneofs.push(slot);
            }
            continue;
        }
        let rust = snake(field.name());
        let repeated = field.label() == prost_types::field_descriptor_proto::Label::Repeated;
        let presence = !repeated && (kind_of(field) == Kind::Message || field.proto3_optional());
        if presence || repeated {
            let _ = write!(ctor, "{rust}: {rust}__, ");
        } else {
            let _ = write!(ctor, "{rust}: {rust}__.unwrap_or_default(), ");
        }
    }
    ctor.push('}');
    let ctor = ctor;

    let _ = write!(
        fields,
        "/// Admitted seed for one protocol message.\npub mod {module}_seed {{\n\
         \x20   use crate::ingress::{{Decoded, DecodeState, RetainedExtent}};\n\
         \x20   use crate::generated::*;\n\
         \x20   use serde::de::{{DeserializeSeed, Error as _, MapAccess, Visitor}};\n\
         \x20   use std::marker::PhantomData;\n\
         \x20   /// Admitted seed for [`crate::generated::{ty}`].\n\
         \x20   pub struct {ty}Seed<'s> {{\n\
         \x20       /// The shared admission state for this decode.\n\
         \x20       pub state: &'s DecodeState<'s, 's>,\n\
         \x20   }}\n\
         \x20   impl<'de, 's> DeserializeSeed<'de> for {ty}Seed<'s> {{\n\
         \x20       type Value = Decoded<crate::generated::{ty}>;\n\
         \x20       fn deserialize<D: serde::Deserializer<'de>>(self, d: D) -> Result<Self::Value, D::Error> {{\n\
         \x20           d.deserialize_map(VisitorImpl {{ state: self.state }})\n\
         \x20       }}\n\
         \x20   }}\n\
         \x20   struct VisitorImpl<'s> {{\n\
         \x20       state: &'s DecodeState<'s, 's>,\n\
         \x20   }}\n\
         \x20   impl<'de, 's> Visitor<'de> for VisitorImpl<'s> {{\n\
         \x20       type Value = Decoded<crate::generated::{ty}>;\n\
         \x20       fn expecting(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {{\n\
         \x20           f.write_str(\"struct {ty}\")\n\
         \x20       }}\n\
         \x20       fn visit_map<A>(self, mut map_: A) -> Result<Self::Value, A::Error>\n\
         \x20       where A: MapAccess<'de>, A::Error: serde::de::Error,\n\
         \x20       {{\n\
         \x20           let state = self.state;\n\
         {defaults}\
         \x20           while let Some(key) = map_.next_key::<GeneratedField<A::Error>>()? {{\n\
         \x20               match key {{\n\
         {duplicate_guards}\
         \x20                   GeneratedField::__Ignore(_) => unreachable!(\"the key visitor never yields __Ignore\"),\n\
         \x20               }}\n\
         \x20           }}\n\
         \x20           let dto = {ctor};\n\
         \x20           let extent = crate::ingress::RetainedExtent::checked_retained_bytes(&dto)\n\
         \x20               .ok_or_else(|| {{\n\
         \x20                   let slot = crate::ingress::ErrorSlot {{\n\
         \x20                       class: crate::ingress::IngressClass::ExtentOverflow,\n\
         \x20                       field: 0,\n\
         \x20                       refusal: None,\n\
         \x20                       extent: 0,\n\
         \x20                       actual: 0,\n\
         \x20                   }};\n\
         \x20                   A::Error::custom(crate::ingress::slot_to_message(\n\
         \x20                       state.record_error(slot).class,\n\
         \x20                   ))\n\
         \x20               }})?;\n\
         \x20           Ok(Decoded::new(dto, extent))\n\
         \x20       }}\n\
         \x20   }}\n\
         \x20   /// One variant per accepted field name; both JSON spellings share it.\n\
         \x20   pub enum GeneratedField<E> {{ {enum_variants} /// Never produced; keeps the enum non-empty for messages with no fields.\n        __Ignore(PhantomData<E>) }}\n\
         \x20   impl<'de, E: serde::de::Error> serde::Deserialize<'de> for GeneratedField<E> {{\n\
         \x20       fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {{\n\
         \x20           struct KeyVisitor<E>(PhantomData<E>);\n\
         \x20           impl<E: serde::de::Error> Visitor<'_> for KeyVisitor<E> {{\n\
         \x20               type Value = GeneratedField<E>;\n\
         \x20               fn expecting(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {{\n\
         \x20                   f.write_str(\"a {ty} field name\")\n\
         \x20               }}\n\
         \x20               fn visit_str<Er: serde::de::Error>(self, v: &str) -> Result<GeneratedField<E>, Er> {{\n\
         \x20                   match v {{\n\
         {aliases}\
         \x20                       _ => Err(Er::custom(\"unknown field\")),\n\
         \x20                   }}\n\
         \x20               }}\n\
         \x20           }}\n\
         \x20           d.deserialize_identifier(KeyVisitor(PhantomData))\n\
         \x20       }}\n\
         \x20   }}\n\
         }}\n\n",
        ctor = ctor,
        enum_variants = field_enum.trim(),
        aliases = aliases,
        duplicate_guards = duplicate_guards,
        defaults = defaults,
    );

    let _ = write!(
        out,
        "{fields}impl RetainedExtent for {ty} {{\n\
         \x20   fn checked_retained_bytes(&self) -> Option<u64> {{\n\
         \x20       let mut total = 0u64;\n\
         {extent}\
         \x20       Some(total)\n\
         \x20   }}\n\
         }}\n\n"
    );
    emit_oneof_extents(out, message);
}

/// Emit one public, one-call wrapper for a message.
///
/// The wrapper owns the whole decode frame: the policy cell, the adapter the parser borrows, the
/// context and the state all live on this function's stack. The input is reborrowed for the
/// shorter frame, which is sound because the returned DTO owns its memory — the outer input
/// lifetime never constrains the local context.
///
/// It is public API in exactly the sense the task requires: a caller passes bytes, a named
/// [`crate::ingress::IngressLimits`] and its own ledger, and gets an owned non-`Clone` `Decoded`.
fn emit_wrapper(out: &mut String, message: &DescriptorProto) {
    let ty = pascal(message.name());
    let module = snake(message.name());
    // The whole decode frame is emitted CONCRETELY per message. That is what makes the input
    // reborrow work: `bytes` is reborrowed for the shorter local frame, the policy cell, adapter,
    // context and state live on this stack, and the returned `Decoded<T>` owns its memory — so the
    // caller's input lifetime never constrains the local context. A generic lifetime-parameterised
    // helper cannot express this; a concrete body can.
    let _ = write!(
        out,
        "/// Decode one `{ty}` from `bytes`, admitted against the caller's policy and ledger.
         ///
         /// # Errors
         ///
         /// [`crate::ingress::IngressError`] carrying a `Copy` `ErrorSlot`. A refusal never
         /// returns a partial DTO and never yields memory the caller did not pay for.
         pub fn decode_{module}(
             bytes: &[u8],
             limits: crate::ingress::IngressLimits,
             ledger: &mut dyn sage_db_types::ledger::SharedLedger,
         ) -> Result<crate::ingress::Decoded<crate::generated::{ty}>, crate::ingress::IngressError> {{
             // Body ceiling FIRST, before the parser is entered.
             if bytes.len() as u64 > limits.body_bytes {{
                 return Err(crate::ingress::IngressError(crate::ingress::ErrorSlot {{
                     class: crate::ingress::IngressClass::BodyCeiling,
                     field: 0,
                     refusal: None,
                     extent: bytes.len(),
                     actual: 0,
                 }}));
             }}
             let policy = core::cell::RefCell::new(crate::ingress::LedgerAdmission::new(ledger));
             let mut adapter = crate::ingress::SharedPolicy(&policy);
             let context = serde_json::admission::AdmissionContext::new(&mut adapter);
             let state = crate::ingress::DecodeState::new(&policy, limits.owned_bytes);
             let seed = crate::ingress::seeds::{module}_seed::{ty}Seed {{ state: &state }};
             let mut deserializer =
                 serde_json::de::Deserializer::from_slice_with_admission(bytes, &context);
             use serde::de::DeserializeSeed as _;
             match seed.deserialize(&mut deserializer) {{
                 Ok(decoded) => match serde_json::de::Deserializer::end(&mut deserializer) {{
                     Ok(()) => Ok(decoded),
                     Err(error) => Err(crate::ingress::IngressError(
                         crate::ingress::classify_parser_error(&error, &state),
                     )),
                 }},
                 Err(error) => Err(crate::ingress::IngressError(
                     crate::ingress::classify_parser_error(&error, &state),
                 )),
             }}
         }}
\n"
    );
}

/// Emit `RetainedExtent` for each oneof enum, so `opt_extent` can measure the active arm.
///
/// prost nests the enum as `{message_module}::{slot}::{Enum}`. Each arm's own extent is measured
/// and summed into the parent's total, so the active variant is never invisible.
fn emit_oneof_extents(out: &mut String, message: &DescriptorProto) {
    let message_module = snake(message.name());
    for (idx, decl) in message.oneof_decl.iter().enumerate() {
        let enm = pascal(decl.name());
        // Skip a SYNTHETIC oneof: prost flattens a `proto3_optional` field to `Option<T>` and
        // emits no enum module for it, so there is nothing to measure.
        let is_synthetic = message.field.iter().any(|f| {
            f.oneof_index.and_then(|i| usize::try_from(i).ok()) == Some(idx) && f.proto3_optional()
        });
        if is_synthetic {
            continue;
        }
        let arms: String = message
            .field
            .iter()
            .filter(|f| f.oneof_index.and_then(|i| usize::try_from(i).ok()) == Some(idx))
            .map(|member| {
                format!(
                    "            crate::generated::{message_module}::{enm}::{variant}(value) => crate::ingress::RetainedExtent::checked_retained_bytes(value),\n",
                    variant = pascal(member.name())
                )
            })
            .collect();
        let _ = write!(
            out,
            "/// Retained extent of the active oneof arm.\nimpl crate::ingress::RetainedExtent for crate::generated::{message_module}::{enm} {{\n    fn checked_retained_bytes(&self) -> Option<u64> {{\n        match self {{\n{arms}        }}\n    }}\n}}\n\n"
        );
    }
}

/// The maker expression producing one element seed of this kind, for `VecSeed`.
fn repeated_element_maker(kind: Kind, elem: &str) -> String {
    match kind {
        Kind::String => {
            "|state| crate::ingress::RepeatedStringSeed { state, field: 0 }".to_string()
        }
        // A repeated message element is NOT nullable in pbjson (`Vec<T>`, not `Vec<Option<T>>`).
        Kind::Message => format!(
            "|state| crate::ingress::ElementMessageSeed::new(crate::ingress::seeds::{}_seed::{elem}Seed {{ state }})",
            snake(elem)
        ),
        _ => format!("|_state| crate::ingress::IntegerSeed::<{elem}>::new()"),
    }
}

/// The prost enum type a field names (`type_name` is fully qualified; take the last segment).
fn enum_type_of(field: &FieldDescriptorProto) -> String {
    pascal(field.type_name().rsplit('.').next().unwrap_or("Enum"))
}

fn elem_type(kind: Kind, field: &FieldDescriptorProto) -> String {
    match kind {
        Kind::Uint32 => "u32".to_string(),
        Kind::Uint64 => "u64".to_string(),
        Kind::String => "String".to_string(),
        Kind::Enum => "i32".to_string(),
        Kind::Message => pascal(field.type_name().rsplit('.').next().unwrap_or("Message")),
    }
}

